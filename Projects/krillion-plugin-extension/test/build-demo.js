// node test/build-demo.js
// Writes test/overlay-demo.standalone.html: overlay-demo.html with src/overlay.js inlined, so it can be
// opened anywhere (including viewers that cannot load sibling files).
const fs = require('node:fs');
const path = require('node:path');

const here = __dirname;
const demo = fs.readFileSync(path.join(here, 'overlay-demo.html'), 'utf8');
const overlay = fs.readFileSync(path.join(here, '..', 'src', 'overlay.js'), 'utf8');
const tag = '<script src="../src/overlay.js"></script>';
if (!demo.includes(tag)) throw new Error('overlay-demo.html no longer references ../src/overlay.js');
const generated = demo
  .replace(tag, () => `<script>\n${overlay}\n</script>`)
  .replace('<!-- Manual harness', '<!-- GENERATED by test/build-demo.js (node test/build-demo.js) - do not edit by hand. Manual harness');
fs.writeFileSync(path.join(here, 'overlay-demo.standalone.html'), generated);
console.log('wrote test/overlay-demo.standalone.html');
